export const presetOf = (idOrName: string | null | undefined): GamePreset | null => {
  const k = (idOrName ?? '').trim().toLowerCase();
  if (!k) return null;
  return GAME_PRESETS.find((g) => g.id === k || g.name.toLowerCase() === k || g.short.toLowerCase() === k) ?? null;
};
