// What the tournament screens know about the games the club runs most. Picking a game sets sensible defaults (team size, best-of, a starting format) and gives the score screen the right words and lists (maps or stages, agents, champions, characters). Everything stays editable and free text is always allowed:
// a game that is not here is just "Other". Lists are suggestions for a dropdown, never a limit.
export interface GamePreset {
  id: string;
  name: string;
  short: string;
  entrant_type: 'solo' | 'team';
  team_size: number;
  best_of: number; // the usual series length
  best_ofs: number[]; // what is offered
  template: string; // the format template to start from (lib/tournaments/stages.ts TEMPLATES)
  unit: string; // what one game of a series is called ("Map", "Game")
  scoreLabel: string; // what the numbers inside a game are ("Rounds", "Stocks left", "Kills")
  maxGameScore?: number; // the score that ends a game, when there is one
  mapLabel: string; // "Map" or "Stage"
  maps: string[];
  pickLabel: string; // "Agent", "Champion", "Hero", "Character"
  picks: string[]; // suggestions for the pick fields (may be empty: free text)
  tips: string[]; // short notes shown while setting up
}

