// A small Byte for places that must stay light (loading, empty lists, the 404): his flat colours merged into one path each and his lines simplified, so it is a few KB where the code's
// drawing (byteArt.ts) is over 150. Writes src/components/Bytecode/miniArt.ts. Usage: node scripts/byte-art/mini.mjs [tolerance=0.008]
import fs from 'fs';

const TOL = +process.argv[2] || 0.008;
const art = fs.readFileSync('src/lib/qr/byteCode/byteArt.ts', 'utf8');
const all = [...art.matchAll(/\{ col: (\d+), d: '([^']*)' \},/g)].map((m) => ({ col: +m[1], d: m[2] }));
const nReg = (art.split('export const EYES')[0].match(/\{ col: \d+, d: '/g) || []).length;
const regions = all.slice(0, nReg);
const strokes = eval(art.match(/export const STROKES[^=]*=\s*(\[[\s\S]*?\]);\s*\n/)[1]);

const dp = (p, t) => {
  if (p.length < 3) return p;
  const a = p[0],
    b = p[p.length - 1];
  let m = 0,
    k = 0;
  const vx = b[0] - a[0],
    vy = b[1] - a[1],
    L = Math.hypot(vx, vy) || 1e-9;
  for (let i = 1; i < p.length - 1; i++) {
    const d = Math.abs((p[i][0] - a[0]) * vy - (p[i][1] - a[1]) * vx) / L;
    if (d > m) {
      m = d;
      k = i;
    }
  }
  return m > t ? [...dp(p.slice(0, k + 1), t).slice(0, -1), ...dp(p.slice(k), t)] : [a, b];
};
const simp = (pts, closed) => {
  if (closed && pts.length > 6) {
    const n = pts.length >> 1;
    return [...dp(pts.slice(0, n + 1), TOL).slice(0, -1), ...dp(pts.slice(n), TOL).slice(0, -1)];
  }
  return dp(pts, TOL);
};
const q = (v) => +v.toFixed(2);
const path = (pts, close) => 'M' + pts.map((p) => `${q(p[0])} ${q(p[1])}`).join('L') + (close ? 'Z' : '');

// flat colours: every region of a colour into one path
const byCol = {};
for (const r of regions) {
  const loops = r.d
    .split('M')
    .filter(Boolean)
    .map((l) =>
      l
        .replace('Z', '')
        .split('L')
        .map((p) => p.trim().split(' ').map(Number)),
    );
  for (const loop of loops) {
    const s = simp(loop, true);
    if (s.length >= 3) (byCol[r.col] ??= []).push(path(s, true));
  }
}
const lenOf = (pts) => pts.reduce((t, p, i) => (i ? t + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) : 0), 0);
const closedOf = (pts) => Math.hypot(pts[0][0] - pts[pts.length - 1][0], pts[0][1] - pts[pts.length - 1][1]) < 0.02;
const inner = strokes
  .filter((s) => !s.ok && lenOf(s.pts) >= 0.12)
  .map((s) => path(simp(s.pts, closedOf(s.pts))))
  .join('');
const outer = strokes
  .filter((s) => s.ok)
  .map((s) => path(simp(s.pts, closedOf(s.pts))))
  .join('');
const out = `// Generated by scripts/byte-art/mini.mjs from byteArt.ts: Byte simplified for small, light uses (see ByteMini.tsx). Do not edit by hand.
export const MINI_FILLS: [number, string][] = ${JSON.stringify(Object.entries(byCol).map(([c, d]) => [+c, d.join('')]))};
export const MINI_INNER = '${inner}';
export const MINI_OUTER = '${outer}';
`;
fs.writeFileSync('src/components/Bytecode/miniArt.ts', out);
console.error('wrote miniArt.ts', out.length, 'bytes at tolerance', TOL);
