// Places the shade patches of the Bytecode: pairs of small squares side by side on Byte's flat colours (one a little lighter, one a little darker; which one is which is a bit). Writes
// src/lib/qr/byteCode/patchArt.ts. Usage: node scripts/byte-art/patches.mjs [pairs=32] [halfSize=0.024] [gap=0.03]
// A pair must lie wholly inside one flat area, clear of every line and of his eyes; the chosen pairs are spread as evenly as possible over him (farthest first), so the bits of one byte are far apart.
import fs from 'fs';

const PAIRS = +process.argv[2] || 32,
  H = +process.argv[3] || 0.024,
  GAP = +process.argv[4] || 0.03;
const art = fs.readFileSync('src/lib/qr/byteCode/byteArt.ts', 'utf8');
const all = [...art.matchAll(/\{ col: (\d+), d: '([^']*)' \},/g)].map((m) => ({ col: +m[1], d: m[2] }));
const nReg = (art.split('export const EYES')[0].match(/\{ col: \d+, d: '/g) || []).length;
const regions = all.slice(0, nReg).map((r) => ({
  col: r.col,
  loops: r.d
    .split('M')
    .filter(Boolean)
    .map((l) =>
      l
        .replace('Z', '')
        .split('L')
        .map((p) => p.trim().split(' ').map(Number)),
    ),
}));
const strokes = eval(art.match(/export const STROKES[^=]*=\s*(\[[\s\S]*?\]);\s*\n/)[1]);
const eyes = eval('(' + art.match(/export const EYE_SHAPES = (\{[\s\S]*?\n?\});/)[1] + ')');
const marks = eval('(' + art.match(/export const MARK_SHAPES = (\{[\s\S]*?\n?\});/)[1] + ')');

const inside = (reg, x, y) => {
  let c = false;
  for (const loop of reg.loops)
    for (let i = 0, j = loop.length - 1; i < loop.length; j = i++) {
      const [xi, yi] = loop[i],
        [xj, yj] = loop[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
};
const regionAt = (x, y) => {
  for (let i = regions.length - 1; i >= 0; i--) if (inside(regions[i], x, y)) return i;
  return -1;
};
const pts = strokes.flatMap((t) => t.pts);
const lineDist = (x, y) => {
  let m = 1e9;
  for (const p of pts) {
    const d = Math.hypot(p[0] - x, p[1] - y);
    if (d < m) m = d;
  }
  return m;
};
const gemRegion = regionAt(marks.gem.x, marks.gem.y);
const sep = 2 * H + GAP;
const cands = [];
for (let y = -0.95; y <= 0.95; y += 0.02)
  for (let x = -0.95; x <= 0.95; x += 0.02) {
    let reg = -2,
      ok = true;
    for (const cx of [x - sep / 2, x + sep / 2]) {
      for (const [dx, dy] of [
        [0, 0],
        [H, H],
        [-H, H],
        [H, -H],
        [-H, -H],
      ]) {
        const r = regionAt(cx + dx, y + dy);
        if (r < 0 || (reg !== -2 && r !== reg)) ok = false;
        reg = r;
        if (!ok) break;
      }
      if (!ok || lineDist(cx, y) < H + 0.008) ok = false;
      if (!ok) break;
    }
    if (!ok || reg === gemRegion) continue;
    if ([eyes.pill, eyes.x].some((f) => Math.hypot(x - f.x, y - f.y) < 0.3)) continue;
    cands.push({ x: +x.toFixed(3), y: +y.toFixed(3) });
  }
// farthest-first, starting from the candidate nearest the middle of the belly
const chosen = [cands.reduce((b, c) => (Math.hypot(c.x, c.y - 0.3) < Math.hypot(b.x, b.y - 0.3) ? c : b))];
while (chosen.length < PAIRS && chosen.length < cands.length) {
  let best = null,
    bd = -1;
  for (const c of cands) {
    const d = Math.min(...chosen.map((o) => Math.hypot(o.x - c.x, o.y - c.y)));
    if (d > bd) {
      bd = d;
      best = c;
    }
  }
  if (bd < sep + 0.01) break;
  chosen.push(best);
}
console.error(`candidates ${cands.length}, placed ${chosen.length} of ${PAIRS}`);
fs.writeFileSync(
  'src/lib/qr/byteCode/patchArt.ts',
  `// Generated by scripts/byte-art/patches.mjs: where the shade patches go. A pair is two squares of half-size PATCH_H side by side, centres PATCH_SEP apart (x - sep/2 and x + sep/2 at y). Do not edit by hand.
export const PATCH_H = ${H};
export const PATCH_SEP = ${+sep.toFixed(4)};
export const PATCH_PAIRS: { x: number; y: number }[] = [
${chosen.map((c) => `  { x: ${c.x}, y: ${c.y} },`).join('\n')}
];
`,
);
